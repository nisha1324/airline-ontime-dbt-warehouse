"""Profile the staged BITRE file and write results/SOURCE_PROFILE.md.

    python scripts/build.py && python scripts/profile_source.py

Reads data/warehouse.duckdb (built by dbt). Every number in the report comes
from a query below, and the output is deterministic: the same snapshot gives
the same file byte for byte.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "warehouse.duckdb"
OUT = ROOT / "results" / "SOURCE_PROFILE.md"
STG = "stg_bitre__otp_monthly"


def fmt(value) -> str:
    if value is None:
        return "–"
    if isinstance(value, float):
        return f"{value:,.0f}" if value == int(value) else f"{value:,.2f}"
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def table(con, sql: str, headers: list[str]) -> str:
    rows = con.sql(sql).fetchall()
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def scalar(con, sql: str):
    return con.sql(sql).fetchone()[0]


def build_report(con) -> str:
    snap = json.loads((ROOT / "data" / "snapshots" / "SNAPSHOT.json").read_text())
    first, last = con.sql(f"select min(month_start), max(month_start) from {STG}").fetchone()
    n_rows = scalar(con, f"select count(*) from {STG}")

    national = scalar(con, f"""
        select sum(sectors_scheduled) from {STG} where row_grain = 'network_all_airlines'""")
    naive = scalar(con, f"select sum(sectors_scheduled) from {STG}")
    leaf = scalar(con, f"""
        select sum(sectors_scheduled) from {STG} where row_grain = 'route_airline'""")
    naive_otp, true_otp = con.sql(f"""
        select
            sum(arrivals_on_time) / sum(sectors_flown),
            sum(arrivals_on_time) filter (where row_grain = 'network_all_airlines')
                / sum(sectors_flown) filter (where row_grain = 'network_all_airlines')
        from {STG}""").fetchone()

    out = []
    out.append("# Source profile: BITRE domestic airline on-time performance\n")
    out.append(
        "Generated by `scripts/profile_source.py` from the dbt staging model "
        f"`{STG}`. Don't edit by hand.\n")
    out.append(
        f"- **Snapshot:** published on data.gov.au {snap['source_last_modified'][:10]}, "
        f"{n_rows:,} rows, {first:%b %Y} to {last:%b %Y} "
        f"({scalar(con, f'select count(distinct month_start) from {STG}')} months).")
    out.append(f"- **Licence:** {snap['licence']}. Source: {snap['attribution']}.")
    out.append(f"- **CSV SHA-256:** `{snap['csv_sha256']}`\n")

    out.append("## 1. One file, four grains\n")
    out.append(
        "Each row is a route or the whole network (\"All Ports\"), for one airline "
        "or for all of them (\"All Airlines\"), for one month. Those four combinations "
        "are stacked in one table:\n")
    out.append(table(con, f"""
        select row_grain, count(*), count(distinct month_start),
               count(distinct route_name) filter (where route_name != 'All Ports-All Ports'),
               count(distinct airline_name), sum(sectors_scheduled)
        from {STG}
        group by row_grain
        order by case row_grain when 'route_airline' then 1 when 'route_all_airlines' then 2
                                when 'network_airline' then 3 else 4 end""",
        ["Grain", "Rows", "Months", "Routes", "Airlines", "Flights scheduled (sum)"]))
    out.append("")

    out.append("## 2. Why the grain matters: the double-counting trap\n")
    out.append(
        "Loaded as-is into a BI tool, a `SUM(Sectors_Scheduled)` card adds all "
        "four grains together. Over the full period:\n")
    out.append("| Measure | Flights scheduled | vs national total |")
    out.append("|---|---|---|")
    out.append(f"| Sum over every row of the raw file | {fmt(naive)} | {naive / national:.2f}× |")
    out.append(f"| National total (`network_all_airlines` rows) | {fmt(national)} | 1.00× |")
    out.append(f"| Sum of route × airline rows only | {fmt(leaf)} | {leaf / national:.2f}× |")
    out.append("")
    out.append(
        f"- The naive sum overstates the national schedule **{naive / national:.2f}×**.")
    out.append(
        f"- Summing only the detailed route rows **understates** it: the published "
        f"routes carry {leaf / national:.0%} of national flights. BITRE lists only "
        "competitive routes with 8,000+ passengers a month, so network totals "
        "have to come from the network rows, not from adding up routes.")
    out.append(
        f"- Ratios move less but still move: on-time arrivals over every row come "
        f"to {naive_otp:.2%}, against {true_otp:.2%} from the national rows.\n")

    out.append("### Share of national flights on the listed routes, by year\n")
    out.append(table(con, f"""
        select year(month_start)::varchar,
               count(distinct route_name) filter (where row_grain = 'route_airline'),
               sum(sectors_scheduled) filter (where row_grain = 'route_airline'),
               sum(sectors_scheduled) filter (where row_grain = 'network_all_airlines'),
               printf('%.1f%%', 100 * sum(sectors_scheduled) filter (where row_grain = 'route_airline')
                     / sum(sectors_scheduled) filter (where row_grain = 'network_all_airlines'))
        from {STG}
        group by 1 order by 1""",
        ["Year", "Listed routes", "Flights on listed routes", "National flights", "Share"]))
    out.append(f"\n{last.year} covers Jan–{last:%b} only.\n")

    out.append("## 3. Airline names\n")
    out.append(
        "Names as published, the cleaned name used downstream (seed "
        "`airline_names`), and when each name appears. Only case and spelling "
        "variants are merged. Rebrands such as Regional Express → Rex Airlines "
        "(Jun → Jul 2021) are kept as published for now; linking them is a "
        "dimension decision (see the plan in the README).\n")
    out.append(table(con, f"""
        select airline_reported, airline_name, count(*),
               strftime(min(month_start), '%b %Y'), strftime(max(month_start), '%b %Y'),
               count(distinct route_name) filter (where row_grain = 'route_airline')
        from {STG}
        where airline_name is not null
        group by all
        order by min(month_start), airline_reported""",
        ["Published name", "Cleaned name", "Rows", "First", "Last", "Listed routes"]))
    out.append("")

    out.append("## 4. Source defects\n")
    out.append(
        "Flagged in staging, never silently fixed. These are the dbt tests that "
        "warn instead of failing; the structural tests (grain labels, keys, "
        "month continuity, routes within networks) all pass.\n")
    out.append(table(con, f"""
        with checks as (
            select 'Cancellations missing' as check_name, 1 as k, * from {STG} where is_cancellations_missing
            union all select 'Departures delayed missing', 2, * from {STG} where departures_delayed is null
            union all select 'Scheduled ≠ flown + cancelled', 3, * from {STG} where not is_schedule_balanced
            union all select 'Flown ≠ departures on time + delayed', 4, * from {STG} where not is_departures_balanced
            union all select 'Flown ≠ arrivals on time + delayed', 5, * from {STG} where not is_arrivals_balanced
            union all select 'Fractional counts', 6, * from {STG} where has_fractional_counts
        )
        select check_name, count(*),
               string_agg(distinct year(month_start)::varchar, ', ' order by year(month_start)::varchar),
               string_agg(distinct coalesce(airline_name, 'All Airlines'), ', '
                          order by coalesce(airline_name, 'All Airlines'))
        from checks
        group by check_name, k
        order by k""",
        ["Check", "Rows", "Years", "Airlines"]))
    out.append("")
    out.append(
        "- Arrivals can legitimately fall short of flights flown: diverted flights "
        "count as neither on time nor delayed.")
    out.append(
        "- Fractional counts (e.g. 33,233.46 departures on time) aren't explained "
        "in BITRE's notes; they are kept as published, so totals for 2009 and "
        "2011 can end in a fraction of a flight.\n")

    con.sql(f"""
        create or replace temp table route_check as
        with airline_rows as (
            select route_name, month_start,
                   sum(sectors_scheduled) as scheduled, sum(sectors_flown) as flown,
                   sum(cancellations) as cancelled, sum(arrivals_on_time) as arr_on_time,
                   sum(departures_on_time) as dep_on_time
            from {STG} where row_grain = 'route_airline' group by all
        ),
        published as (
            select route_name, month_start, sectors_scheduled as scheduled,
                   sectors_flown as flown, cancellations as cancelled,
                   arrivals_on_time as arr_on_time, departures_on_time as dep_on_time
            from {STG} where row_grain = 'route_all_airlines'
        )
        select route_name, month_start,
               p.scheduled as p_scheduled, a.scheduled as a_scheduled,
               p.flown as p_flown, a.flown as a_flown,
               p.cancelled as p_cancelled, a.cancelled as a_cancelled,
               p.arr_on_time as p_arr, a.arr_on_time as a_arr,
               p.dep_on_time as p_dep, a.dep_on_time as a_dep,
               -- rounded: sums of the fractional 2011 values pick up float error
               (round(p.scheduled, 6) is not distinct from round(a.scheduled, 6)
                and round(p.flown, 6) is not distinct from round(a.flown, 6)
                and round(p.cancelled, 6) is not distinct from round(a.cancelled, 6)
                and round(p.arr_on_time, 6) is not distinct from round(a.arr_on_time, 6)
                and round(p.dep_on_time, 6) is not distinct from round(a.dep_on_time, 6)) as matches
        from published p full join airline_rows a using (route_name, month_start)""")
    n_pairs = scalar(con, "select count(*) from route_check")
    n_match = scalar(con, "select count(*) from route_check where matches")
    out.append("### Route totals that don't match their airline rows\n")
    out.append(
        "The `All Airlines` row for a route should equal the sum of that route's "
        f"airline rows. It does in {n_match:,} of {n_pairs:,} route-months "
        f"({n_match / n_pairs:.2%}). The {n_pairs - n_match} exceptions, published "
        "total / sum of airline rows (– = no row):\n")
    out.append(table(con, """
        select route_name, strftime(month_start, '%b %Y'),
               fmt_pair(p_scheduled, a_scheduled), fmt_pair(p_flown, a_flown),
               fmt_pair(p_cancelled, a_cancelled), fmt_pair(p_dep, a_dep),
               fmt_pair(p_arr, a_arr)
        from route_check where not matches
        order by month_start, route_name""",
        ["Route", "Month", "Scheduled", "Flown", "Cancelled",
         "Departed on time", "Arrived on time"]))
    out.append(
        "\nPlan for the marts: rebuild route totals from the airline rows, so a "
        "route's total always equals the sum of its parts in a report.\n")

    con.sql(f"""
        create or replace temp table national_check as
        select n.month_start, n.sectors_scheduled as national, a.networks,
               a.networks - n.sectors_scheduled as gap,
               (select string_agg(x.airline_name, ', ' order by x.airline_name)
                from {STG} x
                where x.row_grain = 'network_airline' and x.month_start = n.month_start
                  and round(x.sectors_scheduled, 6) = round(a.networks - n.sectors_scheduled, 6)
               ) as explained_by
        from {STG} n
        join (select month_start, sum(sectors_scheduled) as networks
              from {STG} where row_grain = 'network_airline' group by all) a
            using (month_start)
        where n.row_grain = 'network_all_airlines'""")
    n_months = scalar(con, "select count(*) from national_check")
    n_gap = scalar(con, "select count(*) from national_check where round(gap, 6) != 0")
    total_gap = scalar(con, "select sum(gap) from national_check")
    out.append("### National totals that leave out an airline\n")
    out.append(
        "The national row should equal the sum of the airline network rows. "
        f"It does in {n_months - n_gap} of {n_months} months. In the other {n_gap}, "
        f"the airline networks add up to {fmt(total_gap)} more flights in total; "
        "where one airline's whole network equals the gap, it is named:\n")
    out.append(table(con, """
        select strftime(month_start, '%b %Y'), national, networks, gap,
               coalesce(explained_by, 'no single airline')
        from national_check where round(gap, 6) != 0 order by month_start""",
        ["Month", "National row", "Sum of airline networks", "Gap", "Gap = network of"]))
    named = con.sql(f"""
        select c.explained_by, count(*) as months,
               strftime(min(f.first_month), '%b %Y') as first_month,
               max(date_diff('month', f.first_month, c.month_start)) as max_age
        from national_check c
        join (select airline_name, min(month_start) as first_month
              from {STG} where row_grain = 'network_airline' group by all) f
            on f.airline_name = c.explained_by
        where round(c.gap, 6) != 0
        group by c.explained_by order by min(c.month_start)""").fetchall()
    parts = [f"{a} ({m} month{'s' if m > 1 else ''}; first reported {first})"
             for a, m, first, _ in named]
    newcomers = all(age < 3 for *_, age in named)
    out.append(
        f"\nWhere a single airline explains the gap ({', '.join(parts)}), "
        + ("it is always in its first three months of reporting: a new airline "
           "left out of the industry total at first. " if newcomers else "see the table. ")
        + "A national KPI built from the airline rows and one taken from the "
        "national row will disagree in these months, so the marts have to pick "
        "one and say so.")
    return "\n".join(out) + "\n"


FMT_PAIR = """
create or replace temp macro fmt_num(x) as
    case when x is null then '–'
         when x = floor(x) then format('{:,}', x::bigint)
         else format('{:,.2f}', x) end;
create or replace temp macro fmt_pair(p, a) as
    case when round(p, 6) is not distinct from round(a, 6) then fmt_num(p)
         else '**' || fmt_num(p) || ' / ' || fmt_num(a) || '**' end;
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--db", type=Path, default=DB)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()
    con = duckdb.connect(str(args.db), read_only=True)
    con.sql(FMT_PAIR)
    report = build_report(con)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report)
    print(f"wrote {args.out.relative_to(ROOT) if args.out.is_relative_to(ROOT) else args.out}")


if __name__ == "__main__":
    main()
